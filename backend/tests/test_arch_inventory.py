"""
Tests for app/architecture/inventory.py — the bounded repository walk.
All tests are fully offline and use tmp_path trees (no committed fixtures).
"""

from pathlib import Path

from app.architecture import inventory as inv_mod


def _write(root: Path, rel: str, content: str = "") -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    return p


# ── skip rules ────────────────────────────────────────────────────────────────


def test_node_modules_and_extra_skip_dirs_are_pruned(tmp_path):
    _write(tmp_path, "node_modules/pkg/index.js", "module.exports = {}")
    _write(tmp_path, "target/debug/x.rs", "fn main() {}")
    _write(tmp_path, "app/main.py", "x = 1\n")
    inv = inv_mod.build_inventory(tmp_path)
    paths = {f.rel_path for f in inv.files}
    assert paths == {"app/main.py"}


def test_binary_file_is_skipped_but_counted_as_discovered(tmp_path):
    (tmp_path / "blob.py").write_bytes(b"\x00\x01\x02binary")
    inv = inv_mod.build_inventory(tmp_path)
    assert inv.files_discovered == 1
    assert inv.files == []
    assert inv.skipped_reasons.get("binary") == 1


def test_lockfile_suffix_is_skipped(tmp_path):
    _write(tmp_path, "poetry.lock", "irrelevant")
    inv = inv_mod.build_inventory(tmp_path)
    assert inv.files == []
    assert inv.skipped_reasons.get("binary_or_lockfile") == 1


# ── secret guard ──────────────────────────────────────────────────────────────


def test_env_file_is_never_opened(tmp_path, monkeypatch):
    _write(tmp_path, ".env", "SECRET_KEY=hunter2-abcdefghijklmnop\n")

    real_open = open

    def guarded_open(path, *a, **kw):
        if str(path).endswith(".env") and "example" not in str(path):
            raise AssertionError(f".env was opened: {path}")
        return real_open(path, *a, **kw)

    monkeypatch.setattr("builtins.open", guarded_open)
    inv = inv_mod.build_inventory(tmp_path)
    assert inv.files == []
    assert inv.skipped_reasons.get("secret_guarded") == 1


def test_env_example_survives_and_is_config_doc(tmp_path):
    _write(tmp_path, ".env.example", "DATABASE_URL=\nSECRET=\n")
    inv = inv_mod.build_inventory(tmp_path)
    assert len(inv.files) == 1
    assert inv.files[0].is_config_doc is True


def test_pem_and_key_files_are_secret_guarded(tmp_path):
    _write(tmp_path, "certs/server.pem", "-----BEGIN CERTIFICATE-----")
    _write(tmp_path, "certs/server.key", "-----BEGIN PRIVATE KEY-----")
    inv = inv_mod.build_inventory(tmp_path)
    assert inv.files == []
    assert inv.skipped_reasons.get("secret_guarded") == 2


