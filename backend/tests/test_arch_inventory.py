# ── walk truncation ───────────────────────────────────────────────────────────


def test_walk_truncates_at_max_discovered_files(tmp_path, monkeypatch):
    monkeypatch.setattr(inv_mod, "ARCH_MAX_DISCOVERED_FILES", 3)
    for i in range(10):
        _write(tmp_path, f"file_{i}.py", "x = 1\n")
    inv = inv_mod.build_inventory(tmp_path)
    assert inv.truncated_walk is True
    assert inv.files_discovered >= 3


def test_symlink_is_not_followed(tmp_path):
    real_dir = tmp_path / "real"
    real_dir.mkdir()
    _write(tmp_path, "real/a.py", "x = 1\n")
    link = tmp_path / "linked"
    try:
        link.symlink_to(real_dir, target_is_directory=True)
    except OSError:
        return  # symlinks unavailable/unprivileged on this platform — nothing to assert
    inv = inv_mod.build_inventory(tmp_path)
    paths = {f.rel_path for f in inv.files}
    assert paths == {"real/a.py"}  # not duplicated via the symlink


